#!/usr/bin/env node

/**
 * Generates nodes/Manyreach/helpers/build-info.ts.
 * Runs via npm's `prebuild` hook.
 * Values come from env vars (Docker build / CI) with sensible fallbacks.
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const distribution =
  process.env.MANYREACH_DISTRIBUTION ||
  (process.env.CI === 'true' ? 'npm' : 'repo');

let buildId = process.env.MANYREACH_BUILD_ID || 'unknown';
if (buildId === 'unknown') {
  try {
    buildId = execSync('git rev-parse --short HEAD', {
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    // No git available; stays 'unknown'
  }
}

const tsContent = `/**
 * AUTO-GENERATED — do not edit. Regenerated by scripts/inject-build-info.js at prebuild time.
 */

export const BUILD_ID = '${buildId}';
export const DISTRIBUTION = '${distribution}';
export const INJECTED_AT = '${new Date().toISOString()}';
`;

const outputPath = path.join(__dirname, '..', 'nodes', 'Manyreach', 'helpers', 'build-info.ts');
fs.writeFileSync(outputPath, tsContent, 'utf-8');
console.log(`Injected build info: BUILD_ID=${buildId}, DISTRIBUTION=${distribution}`);
